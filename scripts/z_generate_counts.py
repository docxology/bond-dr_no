"""Regenerate ``docs/_generated/COUNTS.md`` from a real verification run.

D1 in TODO.md: the counts file used to be maintained by hand — a human ran the
gate and transcribed the numbers. This thin orchestrator replaces that: it runs
the exact gate commands, reads the measured coverage and the pytest summary, and
re-emits ``docs/_generated/COUNTS.md``. It performs no business logic of its own;
it only re-runs the package's own verification and records what came back.

Thin shelling out, no dr_no import: consistent with the ``scripts/`` contract.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
COUNTS_PATH = PACKAGE_ROOT / "docs" / "_generated" / "COUNTS.md"


def _run(cmd: list[str]) -> tuple[int, str]:
    proc = subprocess.run(cmd, cwd=PACKAGE_ROOT, text=True, capture_output=True, check=False)
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def _coverage() -> tuple[str, list[tuple[str, str]]]:
    """Return (total_pct, [(module, pct), ...]) from a fresh coverage run."""
    # JSON reporter needs the coverage plugin's json output; run it explicitly.
    cmd = [
        sys.executable,
        "-m",
        "pytest",
        "tests/",
        "-q",
        "--no-header",
        "--tb=no",
        "--cov=src",
        "--cov-report=json",
    ]
    rc, _out = _run(cmd)
    if rc != 0:
        raise RuntimeError(f"test gate failed (rc={rc}); cannot write honest counts")
    json_path = PACKAGE_ROOT / "coverage.json"
    if not json_path.is_file():
        raise RuntimeError("coverage.json not produced by the coverage run")
    data = json.loads(json_path.read_text(encoding="utf-8"))
    json_path.unlink(missing_ok=True)
    files = data.get("files", {})
    rows: list[tuple[str, str]] = []
    for path, info in files.items():
        pct = info["summary"]["percent_covered"]
        name = Path(path).name.rstrip(".py") if "/dr_no/" in path else path
        rows.append((name, f"{pct:.2f}%"))
    total = data.get("totals", {}).get("percent_covered", 0.0)
    return f"{total:.2f}%", rows


def _passed(out_line: str) -> str:
    m = re.search(r"(\d+) passed", out_line)
    return m.group(1) if m else "?"


def _report() -> None:
    _, pytest_out = _run(
        [
            sys.executable,
            "-m",
            "pytest",
            "tests/",
            "-q",
            "--no-header",
            "--tb=no",
        ]
    )
    passed = _passed(pytest_out)
    total_pct, rows = _coverage()
    _, ruff_check = _run(["uv", "run", "ruff", "check", "src/", "scripts/", "tests/"])
    _, ruff_fmt = _run(["uv", "run", "ruff", "format", "--check", "src/", "scripts/", "tests/"])
    _, mypy = _run(["uv", "run", "mypy", "src/", "scripts/"])

    ruff_ok = "All checks passed" in ruff_check
    fmt_ok = "already formatted" in ruff_fmt
    mypy_ok = "Success" in mypy

    lines = [
        "# CRAB KEY live counts",
        "",
        "<!--",
        "Regenerated by `uv run python scripts/z_generate_counts.py` from a real",
        "verification run; do not hand-edit the numbers here.",
        "-->",
        "",
        "## Test suite",
        "",
        f"- **Tests passed:** {passed}",
        f"- **Coverage (`src/`, line + branch):** {total_pct}",
        "- **Gate:** `uv run pytest tests/ --cov=src --cov-fail-under=90` (>=90% required)",
        "",
        "## Per-module coverage",
        "",
        "| Module | Cover |",
        "| --- | --- |",
    ]
    for name, pct in sorted(rows):
        lines.append(f"| `{name}` | {pct} |")
    lines.append(f"| **TOTAL** | **{total_pct}** |")
    lines += [
        "",
        "## Lint, types, and policy scans",
        "",
        f"- `uv run ruff check src/ scripts/ tests/` — {'clean' if ruff_ok else 'NOT clean'}",
        f"- `uv run ruff format --check src/ scripts/ tests/` — {'clean' if fmt_ok else 'NOT clean'}",
        f"- `uv run mypy src/ scripts/` — {'clean' if mypy_ok else 'NOT clean'}",
    ]
    COUNTS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {COUNTS_PATH}")


if __name__ == "__main__":
    _report()
